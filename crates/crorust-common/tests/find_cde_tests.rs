#[test]
fn test_eocd_with_short_comment() {
    let comment = b"Generated by crorust packaging engine";
    let mut data = vec![0x11; 1024];
    let eocd = create_synthetic_eocd(512, 256, comment);
    let expected_eocd_pos = data.len() as u64;
    data.extend_from_slice(&eocd);

    let mut cursor = Cursor::new(data);
    let pos = locate_central_directory_anchor(&mut cursor).expect("Should find EOCD with comment");
    assert_eq!(pos, expected_eocd_pos);

    let info =
        CentralDirectoryLocator::new(&mut cursor).expect("CentralDirectoryLocator should parse");
    assert_eq!(info.cde_start, expected_eocd_pos);
    assert_eq!(info.cd_start, 512);
}

