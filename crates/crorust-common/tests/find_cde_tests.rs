#[test]
fn test_eocd_with_fake_signature_inside_comment() {
    let mut sneaky_comment = Vec::new();
    sneaky_comment.extend_from_slice(b"Notice the signature here: ");
    sneaky_comment.extend_from_slice(&[0x50, 0x4b, 0x05, 0x06]);
    sneaky_comment.extend_from_slice(b" and more trailing text to complete the comment.");

    let mut data = vec![0x33; 2048];
    let eocd = create_synthetic_eocd(500, 300, &sneaky_comment);
    let expected_eocd_pos = data.len() as u64;
    data.extend_from_slice(&eocd);

    let mut cursor = Cursor::new(data);
    let pos = locate_central_directory_anchor(&mut cursor).expect("Should bypass fake signature");
    assert_eq!(pos, expected_eocd_pos);
}

#[test]
fn test_eocd_file_too_small_fails_fast() {
    for size in [0, 1, 10, 21] {
        let data = vec![0x00; size];
        let mut cursor = Cursor::new(data);
        let res = locate_central_directory_anchor(&mut cursor);
        assert!(res.is_err(), "Expected error for file size {}", size);
        let err_msg = format!("{:#}", res.unwrap_err());
        assert!(
            err_msg.contains("smaller than minimum EOCD header"),
            "Expected clear error message, got: {}",
            err_msg
        );
    }
}

#[test]
fn test_eocd_missing_signature_in_large_file_fails() {
    let data = vec![0x77; 100 * 1024];
    let mut cursor = Cursor::new(data);
    let res = locate_central_directory_anchor(&mut cursor);
    assert!(res.is_err());
    let err_msg = format!("{:#}", res.unwrap_err());
    assert!(err_msg.contains("Could not find central directory end"));
}

#[test]
fn test_eocd_non_standard_trailing_overlay_fallback() {
    let comment = b"Standard comment";
    let mut data = vec![0x44; 1024];
    let eocd = create_synthetic_eocd(256, 128, comment);
    let expected_eocd_pos = data.len() as u64;
    data.extend_from_slice(&eocd);
    data.extend_from_slice(b"EXTRA_OVERLAY_16");

    let mut cursor = Cursor::new(data);
    let pos = locate_central_directory_anchor(&mut cursor)
        .expect("Should fallback to rightmost signature");
    assert_eq!(pos, expected_eocd_pos);
}
